/**
 * `dsh-chat-flow` host 半侧的两段提示文本。
 *
 * 这里只有文本与常量，没有任何接线逻辑，因此可以在测试里逐字断言：
 * 协议正文决定模型「什么时候才允许对用户说话」，提醒正文决定「什么时候必须先出计划」。
 *
 * @module dsh-chat-flow/protocol
 */

/** 系统提示分区的名字（同名分区重复注册会抛错，因此必须是全局唯一的名字）。 */
export const PROTOCOL_SECTION = 'chat-flow:protocol'

/**
 * 分区顺序：排在 `PLAN_POLICY`（500）之后。
 *
 * 计划模式的分区把「只规划、别动手」写在自己的段落里，本协议讲的是「怎么说话、什么时候出计划」，
 * 属于同层次的协作规范，因此紧跟其后；两者顺序互换都不会出错，固定值只为可复现。
 */
export const PROTOCOL_ORDER = 520

/** 注入消息的来源标记用的插件名，与 `name` 导出保持一致。 */
export const PROTOCOL_PLUGIN = 'chat-flow'

/**
 * 「对用户输出」协议 + 「先规划后执行」纪律。
 *
 * 这段文字是模型可见的，所以：只写可执行的规则，不写背景故事；四个时机之外一律要求沉默，
 * 因为界面会把其余动作折叠进「正在处理」——模型多写的旁白会变成折叠块里的噪音。
 */
export const PROTOCOL_TEXT = `## 对话流协议（Chat Flow）

### 对用户输出：只在这四个时机
1. **任务开始时** —— 一句话说明你打算做什么。
2. **输出任务计划时** —— 只讲计划本身。
3. **需要用户审批或决定时** —— 用提问工具提出，不要用正文代替。
4. **任务结束时** —— 汇报结果、证据与遗留问题。

除这四个时机之外不要输出正文。执行命令、调用工具、读写文件、调用 MCP 或插件、检索资料等一律不产生用户可见的长文本：界面会把它们折叠进「正在处理」，展开后才看明细。因此中间过程不要写「现在我来…」「接下来…」这类旁白；需要解释的做法把它写进计划或最终汇报里。

### 先规划，再执行
- 接到需要多步完成的任务时，**第一步先写任务计划**：调用 \`todo_write\` 一次写出完整列表（每项一行祈使句），然后再动手。
- 每完成一项，立刻用 \`todo_write\` 重发整表，把该项标为 \`completed\`，同时把下一项标为 \`in_progress\`。**禁止批量补记**：完成即标记，界面上的任务状态靠这一步更新。
- 只值一步的琐碎请求不写计划，直接做完。
- 界面按这份列表把对话折叠成「任务 → 子对话」，所以**这份列表就是任务边界**，不要再用别的形式复述它。
- 需要用户拍板时先用提问工具问清楚，不要在正文里假设答案。`

/**
 * 「本回合还没写计划」的提醒，由 `agent/pre-step` 在回合第一步注入一次。
 *
 * 写成紧凑的单段：它每个回合最多出现一次，占用的上下文越少越好，所以不复述协议全文，
 * 只给最小可执行指令，并明确「琐事不必写计划」以免模型为了应付而造一个空计划。
 */
export const PLAN_REMINDER_TEXT = `<plan-first>本回合尚未写出任务计划。若这次要做的事不止一步，先调用 todo_write 写出完整任务列表（每项一行祈使句），再开始执行；每完成一项立即重发整表把它标为 completed。只值一步的琐事直接做，不必写列表。</plan-first>`
